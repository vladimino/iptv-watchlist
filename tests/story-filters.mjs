import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';

const ctx=vm.createContext({Date,Intl,Set,Map,URL});
vm.runInContext(fs.readFileSync('public/app.js','utf8').replace(/init\(\);\s*$/,''),ctx);
const now=Date.now();
const film=(id,title,genres,runtime,shows=true)=>({id,title,original:title,aliases:[],year:2020,runtime,genres,directors:[],actors:[],shows:shows?[{start:now,offset:0}]:[]});
ctx.sample=[film('a','Побег Альфа',['Драма'],90),film('b','Побег Бета',['Драма'],120),film('c','Комедия',['Комедия'],80),film('d','Побег Гамма',['Драма'],80),film('e','Побег Дельта',['Драма'],95,false)];
ctx.saved={films:{a:{fingerprint:{plotMechanics:['heist','survival'],moodIds:['tense','dark']}},b:{fingerprint:{plotMechanics:['rescue'],moodIds:['dark']}},c:{fingerprint:{plotMechanics:['heist'],moodIds:['light']}},d:{},e:{fingerprint:{plotMechanics:['heist','unknown_mechanic'],moodIds:['tense']}}}};
vm.runInContext('films=sample;enrichment=saved;WINDOW_START=CUTOFF-72*3600000;WINDOW_END=CUTOFF+24*3600000;genres=["Драма","Комедия"]',ctx);
const ids=()=>Array.from(vm.runInContext('visibleFilms().map(f=>f.id)',ctx));
assert.deepEqual(ids(),['c','a','b','d']);
vm.runInContext('state.mechanics=new Set(["heist","rescue"]);state.moods=new Set(["tense","dark"])',ctx);
assert.deepEqual(ids(),['a','b'],'OR within each group and AND between groups');
vm.runInContext('state.includeUnscheduled=true',ctx);
assert.deepEqual(ids(),['a','b','e'],'same facet logic in full watchlist');
vm.runInContext('state.genres=new Set(["Драма"]);state.maxRuntime=100;state.query="Побег"',ctx);
assert.deepEqual(ids(),['a','e'],'facet filters combine with genre, runtime and search');
vm.runInContext('state.includeUnscheduled=false;state.mechanics=new Set(["heist"]);state.moods=new Set(["light"])',ctx);
assert.deepEqual(ids(),[],'different films cannot satisfy separate AND groups');
vm.runInContext('state.genres=new Set();state.maxRuntime=null;state.query="";state.mechanics=new Set(["unknown_mechanic"]);state.moods=new Set()',ctx);
assert.deepEqual(ids(),[],'unknown mechanics are safely ignored on films');
assert.equal(vm.runInContext('normalizeMood("  МРАЧНЫЙ   ")',ctx),'мрачный');
assert.equal(vm.runInContext('filmFacets(sample[3]).moods.size',ctx),0,'missing fingerprint and prediction do not match');
const elements=Object.fromEntries(['#mechanics','#moods','#mechanics-empty','#moods-empty','#mood-search','#mood-option-count'].map(key=>[key,{innerHTML:'',hidden:false,value:'',textContent:''}]));
ctx.document={querySelector:key=>elements[key],querySelectorAll:()=>[]};
vm.runInContext('state.mechanics=new Set();state.moods=new Set();updateFacetOptions()',ctx);
assert.deepEqual(Array.from(vm.runInContext('mechanics',ctx)).sort(),['heist','rescue','survival']);
assert(!elements['#mechanics'].innerHTML.includes('unknown_mechanic'));
assert.equal((elements['#moods'].innerHTML.match(/value="dark"/g)||[]).length,1,'case and whitespace variants make one mood option');
console.log('Story filters: OR within mechanics/moods, AND across groups, missing values, both scopes and other filters passed');
