import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import {webcrypto} from 'node:crypto';

const ctx=vm.createContext({Date,Map,Set,JSON});
vm.runInContext(fs.readFileSync('src/sources.js','utf8'),ctx);
vm.runInContext(fs.readFileSync('src/discovery.js','utf8'),ctx);
const run=code=>vm.runInContext(code,ctx);
const now=Date.parse('2026-06-15T12:00:00Z');
const show=start=>({channelId:'x',channel:'X',start,end:start+3600000});
ctx.current={key:'now|',title:'Now',normalizedTitle:'now',year:2020,seenInLatestSnapshot:true,shows:[show(now)],lastAiring:now};
ctx.history={key:'old|',title:'Old',normalizedTitle:'old',year:1990,seenInLatestSnapshot:false,shows:[],lastAiring:now-10*86400000,lastSeenAt:now-10*86400000};
ctx.legacy={key:'legacy|',title:'Legacy',normalizedTitle:'legacy',year:2001,lastAiring:now,shows:[show(now)]};
assert.equal(run(`candidateActivity(current,${now})`),'current');
assert.equal(run(`candidateActivity(history,${now})`),'expired');
assert.equal(run(`candidateActivity(legacy,${now})`),'current','a stored show inside the window stays current without the new flag');
assert.equal(run(`resolutionActionability(history,{status:'no_confident_match',attempts:1}, ${now})`),false);
assert.equal(run(`resolutionActionability(current,null,${now})`),true);
const evidence=run('candidateEvidence(current)');
assert.equal(run(`resolutionActionability(current,{status:'no_confident_match',attempts:5,terminalReason:'repeated_uncertain_match',evidenceKey:${JSON.stringify(evidence)}}, ${now})`),false);
ctx.reopened={...ctx.current,shows:[show(now+1000)]};
assert.equal(run(`resolutionActionability(reopened,{status:'no_confident_match',attempts:5,terminalReason:'repeated_uncertain_match',evidenceKey:${JSON.stringify(evidence)}}, ${now})`),true,'a new airing reopens a finished attempt');
const decisions={};
ctx.decisions=decisions;
for(let i=0;i<5;i++)run(`recordUncertain(decisions,current,'no_confident_match',${now}+${i})`);
assert.equal(decisions['now|'].attempts,5);
assert.equal(decisions['now|'].terminalReason,'repeated_uncertain_match');
run(`recordUncertain(decisions,reopened,'no_confident_match',${now}+10)`);
assert.equal(decisions['now|'].attempts,1,'new evidence starts a new attempt series');
assert.equal(decisions['now|'].terminalReason,null);
const ledger=Array.from({length:46000},(_,i)=>({key:'h'+i,title:'H',normalizedTitle:'h',seenInLatestSnapshot:false,shows:[],lastAiring:now-10*86400000}));
ledger.push(ctx.current,ctx.history,{key:'backlog|',title:'Backlog',normalizedTitle:'backlog',seenInLatestSnapshot:false,shows:[],lastAiring:now-3600000});
ctx.ledger=ledger;
const counts=run(`discoveryCounts(ledger,{},${now})`);
assert.equal(counts.ledgerTotal,46003);
assert.equal(counts.currentUnresolved,1);
assert.equal(counts.readyNow,1);
assert.equal(counts.historicalUnresolved,1);
assert.equal(counts.expiredInactive,46001);
assert.equal(ledger.length,46003,'counting does not drop ledger records');

const records=new Map(),etags=new Map();let revision=0,calls=0;
const env={TMDB_API_READ_ACCESS_TOKEN:'test',TMDB_REQUEST_INTERVAL_MS:0,BUCKET:{async get(key){return records.has(key)?{etag:etags.get(key),json:async()=>structuredClone(records.get(key))}:null;},async put(key,value,options={}){const condition=options.onlyIf;if(condition?.etagDoesNotMatch==='*'&&records.has(key)||condition?.etagMatches&&condition.etagMatches!==etags.get(key))return null;records.set(key,JSON.parse(value));etags.set(key,String(++revision));return {etag:etags.get(key)};}}};
const live=vm.createContext({Response,Request,URL,URLSearchParams,AbortSignal,Date,Map,Set,JSON,TextEncoder,Uint8Array,crypto:webcrypto,console,setTimeout,fetch:async()=>{calls++;return new Response(JSON.stringify({total_pages:1,results:[]}));}});
for(const file of ['src/sources.js','src/discovery.js','src/enrichment.js','src/worker.js'])vm.runInContext(fs.readFileSync(file,'utf8').replace('export default','globalThis.worker='),live);
live.env=env;
const hot={key:'fresh|2020',title:'Fresh',normalizedTitle:'fresh',year:2020,duration:100,durations:[100],seenInLatestSnapshot:true,shows:[{channelId:'n',channel:'N',start:Date.now(),end:Date.now()+3600000}],lastAiring:Date.now(),airings:1};
const stale={key:'stale|1999',title:'Stale',normalizedTitle:'stale',year:1999,duration:100,durations:[100],seenInLatestSnapshot:false,shows:[],lastAiring:Date.now()-20*86400000,airings:1};
records.set('programme.json',{runId:'run-1',films:[]});
records.set('epg/discovery-latest.json',{programmeRunId:'run-1',items:[stale,hot]});
records.set('epg/discovered-films.json',{});
let result=await vm.runInContext('resolveDiscoveryBatch(env,{runId:"run-1",films:[]},4)',live);
assert.equal(calls,2,'a historical candidate does not spend a TMDB search');
assert.equal(result.remaining,0);
assert.equal(records.get('epg/discovery-resolution.json')[stale.key],undefined);
assert.equal(records.get('epg/discovery-latest.json').items.length,2);
records.get('epg/discovery-status.json').retryAt=null;
calls=0;
result=await vm.runInContext('resolveDiscoveryBatch(env,{runId:"run-1",films:[]},4)',live);
assert.equal(calls,0,'the same evidence does not retry before its backoff');
const done={key:'done|2020',title:'Done',normalizedTitle:'done',year:2020,duration:100,durations:[100],seenInLatestSnapshot:true,shows:[{channelId:'n',channel:'N',start:Date.now(),end:Date.now()+3600000}],lastAiring:Date.now(),airings:1};
live.done=done;
const doneEvidence=vm.runInContext('candidateEvidence(done)',live);
records.set('epg/discovery-latest.json',{programmeRunId:'run-1',items:[done]});
records.set('epg/discovery-resolution.json',{'done|2020':{status:'no_confident_match',attempts:5,terminalReason:'repeated_uncertain_match',evidenceKey:doneEvidence,retryAt:null}});
records.get('epg/discovery-status.json').retryAt=null;
calls=0;
result=await vm.runInContext('resolveDiscoveryBatch(env,{runId:"run-1",films:[]},4)',live);
assert.equal(result.remaining,0);
assert.equal(calls,0,'a finished attempt does not spend another lookup');
assert.equal(records.get('epg/discovery-resolution.json')['done|2020'].terminalReason,'repeated_uncertain_match');
const pipeline=await vm.runInContext('discoveryPipelineStatus(env)',live);
assert.equal(pipeline.pending,0);
assert.equal(pipeline.unresolved,0);
assert.equal(pipeline.terminalNoMatch,1);
const footer=await vm.runInContext('footerStatus(env)',live);
assert.equal(footer.epgTmdb.pendingRecognition,0);
assert.equal(footer.epgTmdb.ledgerTotal,1);
console.log('Discovery activity: current queue, retained history, attempt limit and large ledger passed');
