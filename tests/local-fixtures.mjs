import assert from 'node:assert/strict';
import {buildLocalFixtures,loadLocalCatalog} from '../scripts/local-fixtures.mjs';

const now=Date.parse('2026-10-20T12:00:00Z');
const catalog=await loadLocalCatalog();
const objects=buildLocalFixtures(catalog,now);
const byKey=new Map(objects.map(item=>[item.key,item.json]));
const programme=byKey.get('programme.json');
assert.equal(programme.films.length,3);
assert.deepEqual(programme.films.map(film=>film.title),['Movie1','Movie2','Movie3']);
assert.deepEqual(programme.people.actors.map(person=>person.name),['Actor1','Actor2']);
assert.deepEqual(programme.films[0].genres,['Genre1']);
const movie1=programme.films[0];
assert.equal(movie1.shows[0].start,now-5*3600000);
assert.ok(movie1.shows[0].start>=programme.window.from&&movie1.shows[1].start<=programme.window.to);
assert.equal(programme.films[2].shows.length,0);
const index=byKey.get('enrichment/view-index.json');
assert.equal(index.films,undefined);
assert.equal(index['movie-1'].actualRating,4.5);
assert.equal(index['movie-1'].fingerprint.execution.pace,'fast');
assert.deepEqual(index['movie-1'].fingerprint.moodLabels,['tense']);
assert.equal(index['movie-1'].fingerprint.fingerprintHash,index['movie-1'].fingerprintHash);
assert.equal(index['movie-2'].prediction.predictedRating,4);
assert.deepEqual(index['movie-2'].prediction.moodLabels,['light']);
assert.equal(index['movie-2'].prediction.fingerprintHash,index['movie-2'].fingerprintHash);
assert.equal(index['movie-2'].prediction.tasteProfileHash,byKey.get('enrichment/profile/current.json').profileHash);
assert.equal(index['movie-3'],undefined);
assert.equal(objects.find(item=>item.key==='started/movie-1.json').customMetadata.started,'true');
assert.equal(JSON.stringify(objects).includes('letterboxd.com'),false);
assert.deepEqual(byKey.get('epg/published-generation.json'),{phase:'published',programmeRunId:'local-fixture',publishedAt:new Date(now).toISOString()});
assert.deepEqual(byKey.get('epg/generations/local-fixture/programme.json'),programme,'the generation copy is the programme');
assert.deepEqual(byKey.get('epg/generations/local-fixture/discovered-films.json'),{});
assert.equal(programme.films[0].tmdbId,'900001');
assert.equal(programme.films[1].tmdbId,undefined);
assert.equal(byKey.get('titles.json')['movie-2'].status,'provisional');
assert.equal(byKey.get('people.json')['actor/actor-2'].name,'Актёр 2');
console.log('Local fixtures: Movie1, Actor1, Genre1, current broadcast window and no personal data passed');
