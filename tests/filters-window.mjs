import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';

const html=fs.readFileSync('public/index.html','utf8');
const app=fs.readFileSync('public/app.js','utf8');
const snapshot=JSON.parse(fs.readFileSync('../sources/cloud-programme.json','utf8'));
const ctx=vm.createContext({console,Intl,Date,Set,Map});
vm.runInContext(app.replace(/init\(\);\s*$/,''),ctx);
ctx.snapshot=snapshot;
const window=vm.runInContext('programmeWindow(snapshot)',ctx);
assert.equal(window.start,snapshot.window.from);
assert.equal(window.end,snapshot.window.to);
assert.equal(window.cutoff,snapshot.window.to-24*3600000);
assert.ok(snapshot.stats.epgEnd<window.end,'The saved programme window can extend beyond observed EPG broadcasts');
vm.runInContext('report=snapshot;WINDOW_START=snapshot.window.from;WINDOW_END=snapshot.window.to;CUTOFF=WINDOW_END-24*3600000;state.to=MAX_YEAR=Math.max(MAX_YEAR,...snapshot.films.map(f=>Number(f.year)||0));films=snapshot.films.map(f=>({...f,shows:f.shows.map(s=>({...s,offset:(s.start-CUTOFF)/3600000}))}));',ctx);
assert.ok(vm.runInContext('films.some(f=>f.shows.some(isArchive))',ctx));
assert.ok(vm.runInContext('films.some(f=>f.shows.some(isFuture))',ctx));
assert.equal(vm.runInContext('isFuture({start:WINDOW_END+1,offset:0})',ctx),false);
const any=vm.runInContext('visibleFilms().length',ctx);
const twoHours=vm.runInContext('state.maxRuntime=120;visibleFilms()',ctx);
assert.ok(twoHours.length>0&&twoHours.length<any);
assert.ok(twoHours.every(f=>Number(f.runtime)>0&&Number(f.runtime)<=120));
const ninety=vm.runInContext('state.maxRuntime=90;visibleFilms()',ctx);
assert.ok(ninety.length<=twoHours.length);
assert.ok(ninety.every(f=>Number(f.runtime)<=90));
assert.equal(vm.runInContext('state.maxRuntime=null;visibleFilms().length',ctx),any);
assert.ok(html.indexOf('id="include-unscheduled"')>html.indexOf('id="runtime-max"'));
assert.match(html,/data-year-from="1900" data-year-to="current"[^>]*>Любой/);
assert.match(html,/data-runtime-max="90"[^>]*>До 90 минут/);
assert.match(html,/data-runtime-max="120"[^>]*>До 2 часов/);
assert.match(html,/data-runtime-max="any"[^>]*>Любые/);
console.log('Filters and saved EPG window: year reset, runtime presets, no-show placement and fixed snapshot dates passed');
