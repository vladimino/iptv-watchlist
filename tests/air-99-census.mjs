import assert from 'node:assert/strict';
import fs from 'node:fs';
import {census} from '../scripts/air-99-census.mjs';

const now=Date.parse('2026-10-24T08:00:00Z');
const show=start=>({channelId:'c',start});
const items=[],decisions={},films={'tmdb_7':{tmdbId:'7',title:'Дешёвый 0',original:'Exact',year:2001,runtime:100,aliases:['Дешёвый 0']}};
function add(key,extra,decision){items.push({key,title:extra.title||key,normalizedTitle:extra.normalizedTitle||key.split('|')[0],year:extra.year??null,durations:extra.durations||[100],shows:[show(now)],seenInLatestSnapshot:true,...extra});if(decision)decisions[key]=decision;}
for(let i=0;i<9;i++)add(`дешёвый ${i}|2001`,{title:`Дешёвый ${i}`,normalizedTitle:`дешевый ${i}`,year:2001,confirmedTmdbId:'7'},{status:'verified',identitySource:'known_epg_alias',tmdbId:'7',evidenceKey:null});
for(let i=0;i<7;i++)add(`ожидает ${i}|2001`,{title:`Ожидает ${i}`,normalizedTitle:`ожидает ${i}`,year:2001,confirmedTmdbId:'8'});
for(let i=0;i<9;i++)add(`без года ${i}|`,{title:`Без года ${i}`,normalizedTitle:`без года ${i}`,year:null});
for(let i=0;i<9;i++)add(`готов ${i}|2001`,{title:`Готов ${i}`,normalizedTitle:`готов ${i}`,year:2001});
for(let i=0;i<9;i++)add(`повтор ${i}|2001`,{title:`Повтор ${i}`,normalizedTitle:`повтор ${i}`,year:2001},{status:'no_confident_match',retryAt:'2026-10-25T00:00:00Z',evidenceKey:null,attempts:1});
for(let i=0;i<7;i++)add(`долг ${i}|2001`,{title:`Долг ${i}`,normalizedTitle:`долг ${i}`,year:2001},{status:'no_confident_match',retryAt:'2026-10-23T00:00:00Z',evidenceKey:null,attempts:1});
for(let i=0;i<7;i++)add(`спор ${i}|2001`,{title:`Спор ${i}`,normalizedTitle:`спор ${i}`,year:2001},{status:'ambiguous',retryAt:null,evidenceKey:null,attempts:1});
for(let i=0;i<4;i++)add(`сериал ${i} серия ${i+1}|`,{title:`Сериал ${i} серия ${i+1}`,normalizedTitle:`сериал ${i} серия ${i+1}`,year:null});
for(let i=0;i<3;i++)add(`длина ${i}|2001`,{title:`Длина ${i}`,normalizedTitle:`длина ${i}`,year:2001},{status:'duration_mismatch',retryAt:null,evidenceKey:null,attempts:1});
decisions.orphan={status:'no_confident_match'};
const report=census(items,decisions,films,now);
assert.equal(report.pipeline.readyNow,9+9+7+3+7);
assert.equal(report.pipeline.retryBackoff,9);
assert.equal(report.pipeline.ambiguous,7);
assert.equal(report.pipeline.nonfilm,4);
assert.equal(report.pipeline.verified,9);
assert.equal(report.orphans,1);
assert.equal(report.quotas.find(row=>row.stratum==='cheap_pass_stored').taken,8);
assert.equal(report.quotas.find(row=>row.stratum==='duration_mismatch').taken,3);
assert.equal(report.quotas.reduce((sum,row)=>sum+row.taken,0),report.sample.length);
assert.ok(report.sample.length<=60);
assert.equal(new Set(report.sample.map(row=>row.key)).size,report.sample.length);
const again=census(items,decisions,films,now);
assert.equal(JSON.stringify(again.sample.map(row=>row.key)),JSON.stringify(report.sample.map(row=>row.key)));
assert.equal(report.sample.find(row=>row.key==='дешёвый 0|2001').catalog.count,1);
const doc=fs.readFileSync('docs/air-99-verdict.md','utf8');
assert.match(doc,/Remaining gaps/);
assert.match(doc,/49715/);
assert.match(doc,/15036/);
assert.match(doc,/14896/);
assert.match(doc,/0 of 5/);
console.log('AIR-99 census sampler passed');
